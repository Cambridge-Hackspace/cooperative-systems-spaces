#!/usr/bin/env node
//
// Regenerates e2e/corpus/endpoints.json from the contract tier's route table.
//
// The work list the fuzz tier iterates has to be complete, and "complete" here
// means every route the router registers. Hand-maintaining a second copy of 164
// rows would guarantee it drifted; deriving it at run time would mean a route
// deleted by accident vanished from the fuzz list too, silently.
//
// So it is generated, committed, and *diffed* by e2e/lint.sh. Adding a route
// fails the lint until somebody regenerates -- which is a deliberate act that
// says "yes, this endpoint should be fuzzed" -- and the generated file is
// reviewable in the diff rather than materialising invisibly inside a test run.
//
// The chain is: server/src/api/** -> checks/tests/route_table_matches.rs ->
// server/tests/common/mod.rs -> this file. Only the middle link is a check; the
// two outer ones are the surface and the work list.
//
//   node e2e/gen-endpoints.mjs           # print
//   node e2e/gen-endpoints.mjs --write   # regenerate the committed file

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TABLE = join(ROOT, 'server/tests/common/mod.rs')
const OUT = join(ROOT, 'e2e/corpus/endpoints.json')

const src = readFileSync(TABLE, 'utf8')
const rows = []
for (const line of src.split('\n')) {
  const m = line.match(/^\s*R\("([A-Z]+)",\s*"([^"]+)",\s*Guard::(\w+)\)/)
  if (m) rows.push({ method: m[1], path: m[2], guard: m[3] })
}

if (rows.length < 150) {
  console.error(`only parsed ${rows.length} rows from ${TABLE}; the parser is broken`)
  process.exit(1)
}

// The fixed UUID the table substitutes for path parameters is restored to a
// placeholder here. The fuzzer needs to know *where* a parameter is so it can
// put hostile values in it; a literal UUID would just be fuzzed as a string
// that happens to look like one, and the id-shaped inputs would never be tried.
const PLACEHOLDER = '00000000-0000-4000-8000-000000000001'
for (const r of rows) {
  r.template = r.path.split(PLACEHOLDER).join('{id}')
  r.params = (r.template.match(/\{id\}/g) ?? []).length
}

rows.sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method))

const doc = {
  _comment:
    'Generated by e2e/gen-endpoints.mjs from server/tests/common/mod.rs. ' +
    'Do not hand-edit: e2e/lint.sh regenerates and diffs, so an edit here is ' +
    'reverted by the next lint run rather than quietly kept.',
  count: rows.length,
  endpoints: rows.map((r) => ({
    method: r.method,
    template: r.template,
    guard: r.guard,
    params: r.params,
  })),
}

const text = JSON.stringify(doc, null, 2) + '\n'
if (process.argv.includes('--write')) {
  writeFileSync(OUT, text)
  console.error(`wrote ${OUT} (${rows.length} endpoints)`)
} else {
  process.stdout.write(text)
}
